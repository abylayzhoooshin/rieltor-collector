"""
paths.py — единое место, где решается, КУДА писать состояние.

ЗАЧЕМ ЭТОТ МОДУЛЬ.
Изначально все файлы состояния (orchestrator_state.json,
fast_known_ids.json, list_meta.json и т.д.) задавались в модулях
относительными именами, то есть писались в текущую рабочую директорию.
Локально это папка проекта — всё работает. В контейнере на Render/Koyeb
рабочая директория (/app) — ЭФЕМЕРНАЯ: она откатывается к содержимому
образа при каждом редеплое и рестарте. Переживает только каталог, на
который смонтирован persistent disk.

Что ломалось конкретно (по каждому файлу):
    orchestrator_state.json  — расписание. Потеря => после каждого
        редеплоя оркестратор считает, что full scan никогда не
        запускался, и стартует полный обход немедленно, независимо от
        того, что он отработал 10 минут назад.
    fast_known_ids.json      — множество уже виденных id. Потеря =>
        первый же fast track после рестарта считает ВСЕ объявления
        новыми. Для сборщика это лишняя работа, а когда сверху появится
        бот-уведомитель — это шквал ложных уведомлений.
    list_meta.json           — признак полноты последнего обхода, от
        которого зависит, разрешено ли помечать missing. Потеря =>
        пропуск пометки на один цикл (безопасная сторона, но всё же
        деградация).
    progress_list.json       — возобновление прерванного обхода списка.
    fast_new_listings.csv,
    krisha_astana_ids.csv,
    krisha_astana_detail.csv — выходные артефакты, теряются молча.

DATA_DIR по умолчанию "." — то есть локально поведение НЕ меняется
(файлы там же, где были). В контейнере DATA_DIR=/app/data совпадает с
точкой монтирования диска, и всё состояние автоматически оказывается
на нём.
"""
import os

DATA_DIR = os.environ.get("DATA_DIR", ".")


def data_path(filename):
    """Путь к файлу состояния внутри DATA_DIR.

    Если filename уже абсолютный (пришёл из отдельной переменной
    окружения — например KRISHA_DB), возвращаем как есть: явная
    настройка всегда важнее общего каталога.
    """
    if os.path.isabs(filename):
        return filename
    os.makedirs(DATA_DIR, exist_ok=True)
    return os.path.join(DATA_DIR, filename)
